package com.github.shikejing.unicodetextcollationjava.normalize;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Arrays;
import java.util.Base64;

/**
 * A versioned, persistable retrieval key for de-duplication and lookup.
 * <p>
 * The key is a fixed-size frame: magic {@code "URET"} (4 bytes) + format version
 * (1 byte) + SHA-256 digest of the folded text (32 bytes), 37 bytes in total. The digest
 * is computed over the NFKC-normalized and case-folded text, so equivalent spellings,
 * case variants and full-width/half-width variants share a key while unrelated texts do
 * not.
 * <p>
 * The format version is embedded in the frame: if the folding rules change, keys
 * generated by an older service version are detected as incompatible instead of silently
 * matching different texts.
 */
public final class RetrievalKey {

    /** Current key framing format version. Bump when the folding rules change. */
    public static final int FORMAT_VERSION = 1;

    private static final byte[] MAGIC = "URET".getBytes(StandardCharsets.US_ASCII);
    private static final int FRAME_LENGTH = 4 + 1 + 32;

    private final byte[] framed;

    private RetrievalKey(byte[] framed) {
        this.framed = framed.clone();
    }

    /**
     * Creates a retrieval key from folded text.
     *
     * @param foldedText the NFKC-normalized and case-folded text
     */
    public static RetrievalKey ofFolded(String foldedText) {
        byte[] digest = sha256(foldedText.getBytes(StandardCharsets.UTF_8));
        byte[] frame = new byte[FRAME_LENGTH];
        int pos = 0;
        System.arraycopy(MAGIC, 0, frame, pos, MAGIC.length);
        pos += MAGIC.length;
        frame[pos] = (byte) FORMAT_VERSION;
        pos += 1;
        System.arraycopy(digest, 0, frame, pos, digest.length);
        return new RetrievalKey(frame);
    }

    /**
     * Reconstructs a retrieval key from its base64 representation.
     *
     * @throws IllegalArgumentException if the frame is corrupted or uses an unsupported
     *                                  format version
     */
    public static RetrievalKey fromBase64(String base64) {
        if (base64 == null || base64.isEmpty()) {
            throw new IllegalArgumentException("empty retrieval key base64 string");
        }
        return fromBytes(Base64.getDecoder().decode(base64));
    }

    /**
     * Reconstructs a retrieval key from its framed binary representation.
     */
    public static RetrievalKey fromBytes(byte[] bytes) {
        if (bytes == null || bytes.length != FRAME_LENGTH) {
            throw new IllegalArgumentException("corrupted retrieval key: bad length");
        }
        int pos = 0;
        for (byte b : MAGIC) {
            if (bytes[pos++] != b) {
                throw new IllegalArgumentException("corrupted retrieval key: bad magic");
            }
        }
        int formatVersion = bytes[pos++] & 0xFF;
        if (formatVersion != FORMAT_VERSION) {
            throw new IllegalArgumentException(
                    "unsupported retrieval key format version: " + formatVersion
                            + " (this service supports version " + FORMAT_VERSION + ")");
        }
        return new RetrievalKey(bytes);
    }

    /**
     * Returns the framed binary representation (a copy).
     */
    public byte[] bytes() {
        return framed.clone();
    }

    /**
     * Returns the framed representation as a base64 string suitable for persistence.
     */
    public String toBase64() {
        return Base64.getEncoder().encodeToString(framed);
    }

    /**
     * Returns the raw SHA-256 digest bytes (a copy).
     */
    public byte[] digest() {
        return Arrays.copyOfRange(framed, 5, FRAME_LENGTH);
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof RetrievalKey other)) {
            return false;
        }
        return Arrays.equals(framed, other.framed);
    }

    @Override
    public int hashCode() {
        return Arrays.hashCode(framed);
    }

    @Override
    public String toString() {
        return "RetrievalKey[v" + FORMAT_VERSION + "]";
    }

    private static byte[] sha256(byte[] data) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(data);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 not available", e);
        }
    }
}
